export async function seedDatabase() {
  try {
    // Check if companies exist
    const existing = await db.select().from(companies);
    if (existing.length > 0) {
      return;
    }

    console.log("Seeding initial SG-SST data into database...");

    for (const comp of initialCompanies) {
      await db.insert(companies).values(comp);
      await db.insert(standards0312).values(initialStandards(comp.id));
      await db.insert(riskMatrixGTC45).values(initialRisks(comp.id));
      await db.insert(annualPlan).values(initialAnnualPlan(comp.id));
      await db.insert(auditFindings).values(initialAuditFindings(comp.id));
      await db.insert(inspections).values(initialInspections(comp.id));
    }

    for (const spec of initialSpecialists) {
      await db.insert(specialists).values(spec);
    }

    console.log("Database seeded successfully!");
  } catch (error) {
    console.error("Error seeding database:", error);
  }
}
